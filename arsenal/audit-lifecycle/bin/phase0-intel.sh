#!/usr/bin/env bash
# phase0-intel.sh — auto-fill the mechanical points of /firmaudit Phase 0 Target Intelligence.
#
# Fills points 1,2,3,4,5,8 of the 8-point intel card automatically.
# Leaves points 6 (crypto primitives), 7 (threat model), 9 (money-flow per mover)
# as the HUMAN/judgment part — the script flags candidates, the operator decides.
#
# Usage:
#   phase0-intel.sh <path-to-repo> [owner/repo] [audit-base-commit]
#     <path-to-repo>     local clone to analyze (required)
#     [owner/repo]       GitHub slug for GHSA/issues + ai-bot-check (optional, inferred from origin)
#     [audit-base-commit] last-audited commit/tag for the post-audit delta (optional, prompted if omitted)
#
# Output: a Markdown intel card to stdout (redirect to PHASE0-INTEL.md).
# No network writes; read-only. gh used read-only if authed, degrades gracefully.

set -uo pipefail

REPO="${1:?usage: phase0-intel.sh <repo-path> [owner/repo] [audit-base-commit]}"
SLUG="${2:-}"
AUDIT_BASE="${3:-}"

[ -d "$REPO" ] || { echo "ERROR: $REPO is not a directory" >&2; exit 2; }
cd "$REPO" || exit 2

AIBOT="$HOME/arsenal/audit-lifecycle/bin/ai-bot-check.sh"

# infer slug from origin if not given
if [ -z "$SLUG" ] && git rev-parse --git-dir >/dev/null 2>&1; then
  origin="$(git remote get-url origin 2>/dev/null || true)"
  SLUG="$(printf '%s' "$origin" | sed -E 's#^.*github.com[:/]##; s#\.git$##')"
fi

hr() { printf '\n---\n\n'; }

echo "# Phase 0 — Target Intelligence (auto-filled)"
echo
echo "- Repo: \`$REPO\`"
echo "- Slug: \`${SLUG:-unknown}\`"
echo "- Generated by phase0-intel.sh (mechanical points 1-5,8; points 6,7,9 are human)"
hr

# ── Point 1: Repo recon ───────────────────────────────────────────────────────
echo "## 1. Repo recon (languages, LOC, modules, deps, cross-chain)"
echo
if command -v tokei >/dev/null 2>&1; then
  echo '```'; tokei --sort lines 2>/dev/null | head -25; echo '```'
elif command -v cloc >/dev/null 2>&1; then
  echo '```'; cloc --quiet . 2>/dev/null | head -25; echo '```'
else
  echo "_(tokei/cloc absent — git ls-files LOC by extension)_"
  echo '```'
  git ls-files 2>/dev/null | grep -E '\.(sol|rs|ts|tsx|js|go|py|move|cairo|vy|circom|nr)$' \
    | sed -E 's/.*\.//' | sort | uniq -c | sort -rn \
    | while read -r n ext; do
        loc=$(git ls-files "*.$ext" 2>/dev/null | xargs wc -l 2>/dev/null | tail -1 | awk '{print $1}')
        printf '  %-6s files=%-5s LOC=%s\n' ".$ext" "$n" "${loc:-?}"
      done
  echo '```'
fi
echo
echo "**Workspace members / sub-packages (recursive — NOT auto in-scope, confirm each):**"
echo '```'
# recursive via git ls-files (respects .gitignore → no node_modules/target dives); fallback to find
manifests() {
  if git rev-parse --git-dir >/dev/null 2>&1; then
    git ls-files 2>/dev/null | grep -E '(^|/)(Cargo\.toml|package\.json|go\.mod|foundry\.toml|hardhat\.config\.[a-z]+|Anchor\.toml|pyproject\.toml)$'
  else
    find . -maxdepth 4 \( -name node_modules -o -name target -o -name .git \) -prune -o \
      -type f \( -name Cargo.toml -o -name package.json -o -name go.mod -o -name foundry.toml \
        -o -name 'hardhat.config.*' -o -name Anchor.toml -o -name pyproject.toml \) -print 2>/dev/null
  fi
}
M="$(manifests | grep -viE '/(node_modules|target|vendor|testdata|examples?|mocks?)/' | sort -u)"
printf '%s\n' "$M" | head -50
nmf=$(printf '%s\n' "$M" | grep -c .)
[ "$nmf" -gt 50 ] && echo "... (+$((nmf-50)) more manifests — multi-module/monorepo; scope is a SUBSET, confirm against the program's in-scope list)"
echo '```'
echo
echo "**Native / external dependencies (root + first sub-package of each ecosystem):**"
echo '```'
# pick the root manifest if present, else the first/shallowest of each type
for type in Cargo.toml go.mod package.json; do
  mf="$(printf '%s\n' "$M" | grep -E "(^|/)$type$" | awk '{print gsub(/\//,"/")"\t"$0}' | sort -n | head -1 | cut -f2-)"
  [ -z "$mf" ] && continue
  echo "# $mf"
  case "$type" in
    Cargo.toml)  grep -hE '^\s*[a-zA-Z0-9_.-]+\s*=\s*("|\{)' "$mf" 2>/dev/null | head -15 ;;
    go.mod)      grep -hE '^\s+[a-z0-9./-]+ v[0-9]' "$mf" 2>/dev/null | head -15 ;;
    package.json) grep -A30 '"dependencies"' "$mf" 2>/dev/null | grep ':' | head -15 ;;
  esac
  echo
done
echo '```'
hr

# ── Point 2: Audit history ────────────────────────────────────────────────────
echo "## 2. Audit history (ON THE CODE IN SCOPE, not protocol total)"
echo
echo "**Audit reports found in repo:**"
echo '```'
find . -type f \( -iname '*.pdf' -o -iname '*audit*' -o -iname '*review*' \) 2>/dev/null \
  | grep -iE 'audit|review|cantina|spearbit|trail|trust|halborn|certik|slowmist|oak|pashov|sherlock|code4rena|c4' \
  | grep -viE 'node_modules|/lib/|/target/' | head -30
echo '```'
echo "- [ ] Count audits per IN-SCOPE component (exploit-primitive-mindset Step 0). Fill manually:"
echo "  - component X → N audits by {firms}"
hr

# ── Point 3: Commit velocity post-audit ───────────────────────────────────────
echo "## 3. Commit velocity post-audit (un-reviewed code = your edge)"
echo
if [ -z "$AUDIT_BASE" ]; then
  echo "_(no audit-base commit supplied — recent tags + last-50 log for you to pick the base)_"
  echo '```'
  echo "# tags:"; git tag --sort=-creatordate 2>/dev/null | head -12
  echo "# recent commits:"; git log --oneline -15 2>/dev/null
  echo '```'
  echo "→ Re-run with the audit-base commit/tag as \$3 to get the delta. **Verify the DEPLOYED source directly — \`git tag --contains\` is insufficient (fixes backport under different SHAs, Rule 4).**"
else
  base_sha="$(git rev-parse --short "$AUDIT_BASE" 2>/dev/null || echo '?')"
  head_sha="$(git rev-parse --short HEAD 2>/dev/null || echo '?')"
  echo "Delta \`$AUDIT_BASE ($base_sha) .. HEAD ($head_sha)\`:"
  echo '```'
  echo "# audit-base resolves to: $base_sha    HEAD: $head_sha"
  echo "# commits ahead: $(git rev-list --count "$AUDIT_BASE"..HEAD 2>/dev/null)"
  echo "# files changed + churn:"
  git diff --stat "$AUDIT_BASE"..HEAD 2>/dev/null | tail -1
  echo "# top-churned in-scope SOURCE files (excl. test/mock/pb/vendor):"
  # exclude generated/codegen + test + vendor noise: .pb.go, proto-rs codegen, *.gen.*, __tests__, snapshots
  churn="$(git diff --numstat "$AUDIT_BASE"..HEAD 2>/dev/null \
    | grep -E '\.(sol|rs|ts|tsx|go|move|cairo|vy)$' \
    | grep -viE '(_test\.|\.test\.|/__tests__/|/test/|/tests/|mock|node_modules|\.pb\.go|\.pb\.gw\.go|/vendor/|/types/|\.gen\.|proto-rs/|/proto/|\.d\.ts$|snapshot)' \
    | awk '{print $1+$2"\t"$3}' | sort -rn)"
  printf '%s\n' "$churn" | head -20
  src_churn_files=$(printf '%s\n' "$churn" | grep -c .)
  echo '```'
  if [ "${src_churn_files:-0}" -eq 0 ]; then
    echo "→ **0 in-scope source files churned post-audit-base.** The commits-ahead are infra/dep bumps (cometbft/cosmos-sdk/indexer), NOT money-flow code. **No fresh edge from drift** — this is a STRONG NO-GO/​WATCH signal for Phase T unless a new in-scope version ships. (dYdX v9.6.3: 111 commits ahead, 0 protocol money-flow churn.)"
  else
    echo "→ These $src_churn_files churned files are post-audit = can't be \"known from audits\" (Rule 4). Prioritize them in the path graph (SC-P-14)."
  fi
  echo
  echo "⚠️ **DEPLOYED-COMMIT VERIFICATION (do this, do not trust the tag or your memory):**"
  echo "   The audit-base above is a LOCAL tag. The actually-DEPLOYED commit can differ (fixes backport under different SHAs — Rule 4, dYdX lesson \`drift-fix-backport-check-tag-contains-insufficient\`). Confirm what validators/mainnet actually run:"
  echo "   - on-chain/app-version query (e.g. \`<chain> q ... | grep version\`, or the node's \`/abci_info\`), or the protocol's release/deployment record;"
  echo "   - then \`git rev-parse <that-commit>\` and re-run point 3 against the TRUE deployed SHA."
  echo "   If your intel/memory names a deployed commit (e.g. \`0a244c30\`) and \`git rev-parse $AUDIT_BASE\` = \`$base_sha\` disagrees → STOP and reconcile before auditing; you may be reading the wrong source."
fi
hr

# ── Point 4: AI-bot check ─────────────────────────────────────────────────────
echo "## 4. AI-bot check (v12-auditor / Olympix / Cantina-bot)"
echo
if [ -n "$SLUG" ] && [ -x "$AIBOT" ]; then
  echo '```'
  "$AIBOT" "$SLUG" 2>&1 | head -20
  rc=$?
  echo "# ai-bot-check exit: $rc  (1 = bot detected)"
  echo '```'
  echo "→ If bot detected: V12-class (access-control, input-validation, reentrancy, unchecked-arith, inline-asm DoS, transient-storage reuse, tokenIn==tokenOut) carries STRUCTURAL dup-risk → steer to logic / economic / design / crypto / cross-chain."
else
  echo "_(skipped: slug unknown or ai-bot-check.sh absent)_  Run manually: \`ai-bot-check.sh <owner/repo>\`"
fi
hr

# ── Point 5: Issue tracker / GHSA history ─────────────────────────────────────
echo "## 5. Issue tracker / GHSA / prior public vulns (Rule 10 / KILL-GATE Q10)"
echo
if [ -n "$SLUG" ] && command -v gh >/dev/null 2>&1; then
  echo "**Security advisories:**"
  echo '```'
  gh api "repos/$SLUG/security-advisories" --jq '.[] | "\(.ghsa_id)\t\(.severity)\t\(.summary)"' 2>/dev/null | head -15 \
    || echo "(none public / not accessible)"
  echo '```'
  echo "**Open+closed issues/PRs mentioning security terms:**"
  echo '```'
  gh search issues --repo "$SLUG" --match title 'vulnerability OR exploit OR security OR overflow OR reentrancy' --limit 15 \
    --json number,title,state --jq '.[] | "#\(.number)\t\(.state)\t\(.title)"' 2>/dev/null | head -15 \
    || echo "(gh search unavailable)"
  echo '```'
else
  echo "_(skipped: slug unknown or gh absent)_  Check manually: GH Issues/PRs/Advisories, CVE, C4/Cantina/Sherlock. **MANDATORY for forks/derivatives.**"
fi
hr

# ── Point 8: Real cross-chain surface ─────────────────────────────────────────
echo "## 8. Real cross-chain surface (each chain = different primitive + tx path)"
echo
echo '```'
{ grep -rliE 'pragma solidity|SPDX'                          --include='*.sol'  . 2>/dev/null | head -1 | sed 's/.*/EVM (Solidity) present/'
  grep -rliE 'anchor_lang|solana_program|declare_id'         --include='*.rs'   . 2>/dev/null | head -1 | sed 's/.*/Solana (Anchor\/Rust) present/'
  grep -rliE 'cosmwasm|cosmos-sdk'                            . 2>/dev/null | head -1 | sed 's/.*/Cosmos present/'
  grep -rliE 'aptos_framework|module .*::'                    --include='*.move' . 2>/dev/null | head -1 | sed 's/.*/Move (Aptos\/Sui) present/'
  grep -rliE 'starknet|%lang'                                 --include='*.cairo' . 2>/dev/null | head -1 | sed 's/.*/Cairo (Starknet) present/'
  grep -rliE 'frame_support|substrate'                        --include='*.rs'   . 2>/dev/null | head -1 | sed 's/.*/Substrate present/'
  grep -rliE 'bitcoin|bitcoinjs|secp256k1.*bitcoin|psbt'      . 2>/dev/null | head -1 | sed 's/.*/Bitcoin present/'; } | sort -u
echo '```'
echo "→ Cross-language line refs are load-bearing: verify file:line resolves on BOTH sides at the cited commit (Rule, Hyperbridge F-002 lesson)."
hr

# ── Human-only points (flagged, not auto-filled) ──────────────────────────────
echo "## 6. Crypto primitives present  — HUMAN (read the code)"
echo "Candidates auto-grepped (verify):"
echo '```'
grep -rhoE 'secp256k1|ed25519|ristretto|bls12_?381|bn254|schnorr|bip0?340|ecdsa|eddsa|bip32|bip39|bip44|slip-?0010|frost|threshold|musig|keccak256|sha256|blake2|poseidon' \
  . 2>/dev/null | grep -viE 'node_modules|/target/' | sort | uniq -c | sort -rn | head -20
echo '```'
echo
echo "## 7. Implicit threat model — HUMAN"
echo "- [ ] Pure non-custodial? client-side key derivation? RPC interaction?"
echo "- [ ] Operator/keeper EOA that signs on-chain in response to off-chain events (the upshift seam)?"
echo "- [ ] Who can move funds, under what trust assumption?"
echo
echo "## 9. Money-flow prefilter — HUMAN (the OKX F-007 gate, applied NOW not Week 8)"
echo "- [ ] For EVERY identified fund-mover, can a candidate finding produce a \`loss = \$X\` PoC line?"
echo "      If a whole surface can never produce loss=\$X → it is signature-hygiene / state-misrep → deprioritize at Phase 0."
hr
echo "## Target-profile classification (decides the plan path)"
echo "- [ ] Path A crypto/cross-chain · Path B off-chain orchestration · Path C web/API · Path D SC>\$50K hardened · or UNION (mixed-profile, Rule 40 — run the union, never drop a leg)"
