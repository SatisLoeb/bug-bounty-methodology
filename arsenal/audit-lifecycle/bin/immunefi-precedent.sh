#!/usr/bin/env bash
# immunefi-precedent.sh — surface the Immunefi audit-comp pattern bank AT THE MOMENT
# the finding's gates are instantiated, instead of relying on the operator remembering
# to query it.
#
# Auto-invoked by on-finding.sh --stage 2 (where kill-gate Q10, severity-commit and the
# weight-card are created) — the exact three gates this corpus serves:
#   --dup       -> Gate 2 / kill-gate Q10  (has this mechanism already been reported?)
#   --precedent -> D8/W5 weight-card       (what floor did the PAYER itself award this class?)
#
# Keywords come from the "One-line title" the operator filled in the stage-1 scope-check,
# so nothing extra has to be typed. Override with --kw "<words>".
#
# NON-BLOCKING BY DESIGN. This is an informational surface, not a gate. A missing corpus,
# an unfilled title or a query error must never stop a pipeline that 9 skills depend on;
# every failure path exits 0 with a printed reason.
set -uo pipefail

WS=""; FID=""; KW=""
while [ $# -gt 0 ]; do
  case "$1" in
    --kw) shift; KW="${1:-}";;
    --workspace) shift; WS="${1:-}";;
    -h|--help) sed -n '2,17p' "$0"; exit 0;;
    *) if [ -z "$FID" ]; then FID="$1"; elif [ -z "$WS" ]; then WS="$1"; fi;;
  esac
  shift || true
done

[ -n "$FID" ] || { echo "usage: $0 <FINDING_ID> [workspace] [--kw \"words\"]" >&2; exit 0; }
WS="${WS:-$PWD}"
FINDINGS_DIR="$WS/findings"
[ -d "$FINDINGS_DIR" ] || FINDINGS_DIR="$WS"
OUT="$FINDINGS_DIR/${FID}-immunefi-precedent.md"

QUERY="$HOME/arsenal/tools/immunefi-corpus-query.sh"
if [ ! -e "$QUERY" ]; then
  echo "[immunefi-precedent] corpus tool absent ($QUERY) — skipped, not a failure"; exit 0
fi

# Derive keywords from the scope-check one-liner unless given explicitly.
if [ -z "$KW" ]; then
  SC="$FINDINGS_DIR/${FID}-scope-check.md"
  if [ -f "$SC" ]; then
    KW="$(grep -m1 -E '^One-line title:' "$SC" | sed -E 's/^One-line title:[[:space:]]*//')"
  fi
fi
# strip the unfilled template placeholder
case "$KW" in
  \[*|"") KW="";;
esac
# drop filler words so the query rides on mechanism terms, not grammar
KW="$(printf '%s' "$KW" | tr 'A-Z' 'a-z' \
  | sed -E 's/[^a-z0-9 ._-]+/ /g; s/\b(the|a|an|of|to|in|is|are|can|be|by|for|and|or|not|with|on|at|from|that|this|it|its|when|if|due|via)\b/ /g; s/ +/ /g; s/^ //; s/ $//')"

if [ -z "$KW" ]; then
  cat > "$OUT" <<EOF
# Immunefi precedent — $FID

NOT RUN: no usable keywords. The scope-check "One-line title" was empty or still the
template placeholder.

Fill it, then re-run:

    $0 $FID $WS

or pass terms directly:

    $0 $FID $WS --kw "unbonding entries griefing dust"
EOF
  echo "[immunefi-precedent] no keywords (scope-check title unfilled) — wrote a re-run stub"
  exit 0
fi

{
  echo "# Immunefi precedent — $FID"
  echo
  echo "Auto-generated by on-finding.sh --stage 2. Query terms (from the scope-check one-liner):"
  echo
  echo '```'
  echo "$KW"
  echo '```'
  echo
  echo "## Gate 2 / kill-gate Q10 — already reported?"
  echo
  echo "A hit is a LEAD, not a verdict. Compare MECHANISM, not vocabulary: same words +"
  echo "different mechanism is not a dup, and a dup-as-class re-opens on a NEW impact."
  echo
  echo '```'
  bash "$QUERY" --dup $KW 2>&1 | head -32
  echo '```'
  echo
  echo "## D8 / W5 weight-card — what floor did the payer award this class?"
  echo
  echo "This is FIRST-PARTY data: the severity on each page is what Immunefi actually"
  echo "awarded, not a hunter's claim. Use it to set the SEVERITY-COMMIT floor, and argue"
  echo "the ceiling in the body."
  echo
  echo '```'
  bash "$QUERY" --precedent $KW 2>&1 | head -30
  echo '```'
  echo
  echo "## Next"
  echo
  echo '- open the strongest exemplars above before committing a floor'
  echo "- \`immunefi-corpus-query.sh --show <report_id>\` for the full report + PoC"
  echo '- `immunefi-corpus-query.sh --impacts <kw>` for the verbatim in-scope VSC strings'
} > "$OUT" 2>&1

echo "[immunefi-precedent] wrote $OUT  (terms: $KW)"
exit 0
